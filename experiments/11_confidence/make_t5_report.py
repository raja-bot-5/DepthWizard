#!/usr/bin/env python3
"""docs/building_heights.md + src/depthwizard/calibration/height_confidence_evidence.json from the T5 runs.

  python experiments/11_confidence/make_t5_report.py runs/exp11_confidence/<run> runs/exp11_shadows/<run> runs/buildings/<run>
The evidence JSON is what the API/UI quote next to a confidence level (measured error per level), so the numbers
shown to users come from a named run, not from code.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITES = {"A_urban": "A urban", "B_hilly_forest": "B hilly forest", "C_sparse": "C sparse"}


def f(v, d=2):
    return "–" if v is None else f"{v:.{d}f}"


def pooled(items):
    """Cell-weighted pooled RMSE and bias over sites."""
    n = sum(m["n"] for m in items if m.get("n"))
    if not n:
        return {"n": 0}
    rmse = math.sqrt(sum(m["n"] * m["rmse"] ** 2 for m in items if m.get("n")) / n)
    bias = sum(m["n"] * m["bias"] for m in items if m.get("n")) / n
    return {"n": n, "rmse": rmse, "bias": bias}


def main() -> None:
    conf_run, shad_run, bld_run = (Path(a).resolve() for a in sys.argv[1:4])
    C = json.loads((conf_run / "confidence_eval.json").read_text())
    S = json.loads((shad_run / "metrics.json").read_text())
    B = json.loads((bld_run / "metrics.json").read_text())
    pool = {lv: pooled([C[s]["object_cells_gt2m"][lv] for s in C]) for lv in ("low", "medium")}
    evidence = {"source": str(conf_run.relative_to(ROOT)), "scope": "object cells (LiDAR nDSM > 2 m), 2 m grid, "
                "held-out blocks, 3 NAIP sites (Boulder, USA; not Cartosat)",
                "levels": {lv: {"n_cells": p["n"], "rmse_m": round(p["rmse"], 2), "bias_m": round(p["bias"], 2)}
                           for lv, p in pool.items()}}
    (ROOT / "src" / "depthwizard" / "calibration" / "height_confidence_evidence.json").write_text(
        json.dumps(evidence, indent=2))

    L = ["# Building and object heights: confidence and shadows (Phase 11 T5)", "",
         "Generated by `experiments/11_confidence/make_t5_report.py` from "
         f"`{conf_run.relative_to(ROOT)}`, `{shad_run.relative_to(ROOT)}` and `{bld_run.relative_to(ROOT)}`.", "",
         "*Height above ground* = DSM − an estimated local ground. It is **derived, not measured**. The truth used "
         "here is LiDAR DSM − DTM from the same 2013 survey, so the datum cancels. Scores are on held-out test blocks only.", "",
         "## 1. Confidence levels", "",
         "Each derived height gets **low** or **medium**. It is low if any of these apply: no visible ground within "
         "the 60 m window; ESA WorldCover tree cover; water; or height < 2 × the DSM's 1-σ uncertainty. "
         "**There is no *high* level:** no derived height has been validated to that standard.", "",
         "### Error per level (object cells, LiDAR nDSM > 2 m)", "",
         "| Site | Low: n / bias / RMSE (m) | Medium: n / bias / RMSE (m) |", "|---|---|---|"]
    for s in C:
        lo, me = C[s]["object_cells_gt2m"]["low"], C[s]["object_cells_gt2m"]["medium"]
        L.append(f"| {SITES[s]} | {lo['n']:,} / {f(lo.get('bias'))} / {f(lo.get('rmse'))} | "
                 f"{me['n']:,} / {f(me.get('bias'))} / {f(me.get('rmse'))} |")
    L.append(f"| **Pooled** | {pool['low']['n']:,} / {f(pool['low']['bias'])} / {f(pool['low']['rmse'])} | "
             f"{pool['medium']['n']:,} / {f(pool['medium']['bias'])} / {f(pool['medium']['rmse'])} |")
    L += ["", "### Per reason (object cells)", "", "| Site | Reason | n | bias (m) | RMSE (m) |", "|---|---|---|---|---|"]
    for s in C:
        for k, v in C[s]["object_cells_gt2m"]["by_reason"].items():
            L.append(f"| {SITES[s]} | {k.split(' (')[0]} | {v['n']:,} | {f(v.get('bias'))} | {f(v.get('rmse'))} |")
    L += ["", "### Per building (OSM footprints ≥ 50 m², majority level)", "",
          "| Site | Low: n / bias / RMSE / r | Medium: n / bias / RMSE / r |", "|---|---|---|"]
    for s in C:
        b = C[s].get("buildings_held_out")
        if not b:
            continue
        cell = lambda m: (f"{m['n']} / {f(m.get('bias'))} / {f(m.get('rmse'))} / {f(m.get('pearson_r'))}"
                          if m.get("rmse") is not None else f"{m['n']} (too few)")
        L.append(f"| {SITES[s]} | {cell(b['low'])} | {cell(b['medium'])} |")
    L += ["", "**What the levels do and do not tell you:**", "",
          "- They flag real failure regimes. Forest is almost entirely low (canopy hides the ground). Water is flagged "
          "(both the estimate and the LiDAR DTM are unreliable there). *Height below 2σ* on cells where LiDAR sees "
          "an object marks **missed objects**, with some of the largest errors.",
          f"- **Medium does not mean accurate.** Pooled over object cells, medium is only slightly better than low "
          f"(RMSE {f(pool['medium']['rmse'])} vs {f(pool['low']['rmse'])} m). At the urban site the order reverses "
          "(buildings: low 4.40, medium 4.92 m). Every derived height carries a 2–4 m underestimate, because the "
          "model detail is scaled by one factor fitted at 30 m. No per-pixel flag can see that. The API and UI "
          "therefore show the measured error for each level next to the level itself "
          "(`height_confidence_evidence.json`).", "",
          "## 2. Shadow-based building heights (prototype)", "",
          "height = shadow length × tan(sun elevation). The shadow runs from the OSM footprint edge along the "
          "anti-sun direction; the 75th percentile of runs is used.", "",
          "| | value |", "|---|---|",
          f"| NAIP STAC time | {S['sun']['nominal_16z']['time_utc']} (a round hour: possibly nominal, UNKNOWN) → sun az "
          f"{S['sun']['nominal_16z']['sun_azimuth_deg']}°, el {S['sun']['nominal_16z']['sun_elevation_deg']}° |",
          f"| Shadow direction measured from the image | sun az {S['sun']['measured']['sun_azimuth_deg']}° → solved "
          f"{S['sun']['measured']['solved_time_utc']}, el {S['sun']['measured']['sun_elevation_deg']}° (peak contrast "
          f"{f(S['sun']['measured']['contrast'])}) |",
          f"| Shadow mask | 3-class Otsu darkest class minus vegetation, {100 * S['sun']['shadow_fraction']:.1f} % of the "
          "scene. Chosen by a label-free criterion (azimuth-peak contrast), not by LiDAR. Other detectors gave sun "
          "azimuths of 94–109°. |", "",
          f"Held-out buildings at site A (n = {S['n_test_buildings']}; {S['n_common']} have a measurable shadow):", "",
          "| Estimate | coverage | bias (m) | RMSE (m) | r | on the common buildings: RMSE / r |", "|---|---|---|---|---|---|"]
    names = {"c2": "current derived height (c2)", "shadow": "shadow, measured sun", "shadow16z": "shadow, nominal 16:00Z sun",
             "c2xk": f"c2 × k (k = {f(S['k_from_fit_buildings'])} from fit-block shadows)", "hybrid": "shadow where clean, else c2"}
    for k, lab in names.items():
        r = S["results"][k]
        a, c = r["all_available"], r["on_common_buildings"]
        L.append(f"| {lab} | {r['coverage']} | {f(a['bias'])} | {f(a['rmse'])} | {f(a['pearson_r'])} | "
                 f"{f(c['rmse'])} / {f(c['pearson_r'])} |")
    L += ["", "**Decision: shadows are NOT used for calibration.** None of the shadow variants beats the current method "
          "on held-out buildings, which was the condition for using them. Shadow length barely tracks LiDAR height "
          "(r ≈ 0.1). The visible causes:",
          "- NAIP is orthorectified to terrain, not true-ortho. Roofs lean over and hide part of their own shadows. The "
          "detected shadows are 1–5 px slivers, where 7–14 px are expected.",
          "- OSM outlines follow roofs, not wall bases.",
          "- Much of the dark area is courtyards and roof structure inside footprints.",
          "- Buildings here are mostly 3–8 m tall, only a few pixels of shadow. LiDAR is from 2013, the image from 2021.",
          "The module (`calibration/shadows.py`, with 6 tests) stays as a prototype. THIS SHOULD BE TESTED on "
          "Cartosat-2S, whose metadata carries sun angles and whose viewing geometry is known.", "",
          "## 3. Baseline: derived building heights per method (A6c)", "",
          "| Site | Method | n | bias (m) | RMSE (m) | NMAD (m) | r |", "|---|---|---|---|---|---|---|"]
    for s, d in B["results"].items():
        for mname, v in d.items():
            if mname == "osm" or "overall" not in v or not v["overall"].get("n"):
                continue
            o = v["overall"]
            L.append(f"| {SITES[s]} | {mname} | {o['n']} | {f(o['bias'])} | {f(o['rmse'])} | {f(o['nmad'])} | {f(o['pearson_r'])} |")
    L += ["", f"Footprints: {B['attribution']}.", ""]
    (ROOT / "docs" / "building_heights.md").write_text("\n".join(L))
    print("wrote docs/building_heights.md; evidence:", json.dumps(evidence["levels"]))


if __name__ == "__main__":
    main()
